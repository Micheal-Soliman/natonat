// Default export for backwards compatibility (English)
export const articles = articlesEn;

export function getArticlesByLocale(locale: string): Article[] {
  return locale === 'ar' ? articlesAr : articlesEn;
}

export function getArticleBySlug(slug: string, locale: string = 'en'): Article | undefined {
  const articles = getArticlesByLocale(locale);
  return articles.find(article => article.slug === slug);
}

export function getFeaturedArticles(locale: string = 'en'): Article[] {
  const articles = getArticlesByLocale(locale);
  return articles.filter(article => article.featured);
}

export function getLatestArticles(count: number = 3, locale: string = 'en'): Article[] {
  const articles = getArticlesByLocale(locale);
  return articles
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
    .slice(0, count);
}

export function getArticlesByCategory(category: string, locale: string = 'en'): Article[] {
  const articles = getArticlesByLocale(locale);
  return articles.filter(article => article.category === category);
}

export function getAllCategories(locale: string = 'en'): string[] {
  const articles = getArticlesByLocale(locale);
  return [...new Set(articles.map(article => article.category))];
}
